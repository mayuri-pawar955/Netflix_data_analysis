"""RECOMMENDATION"""

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import linear_kernel

# Combine key metadata features into a single text string
df['soup'] = (
    df['listed_in'] + ' ' +
    df['director'].replace('Unknown Director', '') + ' ' +
    df['country'].replace('Unknown Country', '') + ' ' +
    df['rating']
)

# Compute TF-IDF matrix
tfidf = TfidfVectorizer(stop_words='english')
tfidf_matrix = tfidf.fit_transform(df['soup'])

# Compute cosine similarity matrix
cosine_sim = linear_kernel(tfidf_matrix, tfidf_matrix)

# Map titles to DataFrame indices
indices = pd.Series(df.index, index=df['title'].str.lower()).drop_duplicates()

def recommend(title, top_n=5):
    title_key = title.strip().lower()
    if title_key not in indices:
        return f"'{title}' not found in dataset."
    idx = indices[title_key]
    sim_scores = sorted(list(enumerate(cosine_sim[idx])), key=lambda x: x[1], reverse=True)[1:top_n+1]
    rec_indices = [i[0] for i in sim_scores]
    return df[['title', 'type', 'release_year', 'rating', 'listed_in']].iloc[rec_indices]

# Test the recommender
recommend('Midnight Mass')

